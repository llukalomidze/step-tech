const DICTS: Record<Lang, Dict> = { en, ka };

@Injectable({ providedIn: 'root' })
export class TranslationService {
  private readonly _lang = signal<Lang>(this.read());
  readonly lang = this._lang.asReadonly();
  readonly dict = computed<Dict>(() => DICTS[this._lang()]);

  setLang(lang: Lang): void {
    this._lang.set(lang);
    document.documentElement.setAttribute('lang', lang);
    try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
  }

  toggle(): void {
    this.setLang(this._lang() === 'en' ? 'ka' : 'en');
  }

  /** Lookup current value for a key. Returns the key itself if missing. */
  t(key: string): string {
    return this.dict()[key] ?? key;
  }

  private read(): Lang {
    try {
      const raw = localStorage.getItem(STORAGE_KEY);
      if (raw === 'ka' || raw === 'en') {
        document.documentElement.setAttribute('lang', raw);
        return raw;
      }
    } catch { /* ignore */ }
    return 'en';
  }
}
